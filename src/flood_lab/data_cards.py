"""Data cards (FG3): ``docs/flood/data-cards/<id>.md`` and an index, from the facts files.

    python -m flood_lab.data_cards

Generated, never typed: a card is rewritten from ``src/flood_lab/facts/<id>.toml`` (and, for a
source with a second reader, its record). The output depends on the committed files only, so two
runs write the same bytes. Every string from a facts file is escaped: it is text from web pages.
"""

from __future__ import annotations

import html
import re
import sys
from pathlib import Path

from lab_common.io import write_text_atomic

from . import paths
from .facts import REQUIRED, Source, level_words, load_all, summary

#: first line of every generated card; only files that start with it are ever removed
MARKER = "<!-- generated by flood_lab.data_cards from src/flood_lab/facts/; do not edit -->"
INDEX = "README.md"
LABELS = {
    "identifier": "Identifier",
    "address": "Address",
    "licence": "Licence",
    "fields": "Fields",
    "coverage_space": "Coverage in space",
    "coverage_time": "Coverage in time",
    "release": "Release",
    "checksum": "Checksum",
}
_MD_SPECIAL = re.compile(r"([\\`*_\[\]#|~])")
_URL = re.compile(r"^https?://[^\s<>\"'`|]+$")


def cell(text: str) -> str:
    """Text made safe for a Markdown table cell: no markup, no column break, no line break."""
    escaped = _MD_SPECIAL.sub(r"\\\1", html.escape(text.strip(), quote=True))
    return "<br>".join(line for line in escaped.splitlines()) or "–"


def link(url: str) -> str:
    url = url.strip()
    if not url:
        return "–"
    return f"<{url}>" if _URL.match(url) else cell(url)


def label(name: str) -> str:
    return LABELS.get(name, name.replace("_", " "))


def _passage(name: str, passage: str) -> list[str]:
    if not passage.strip():
        return []
    return [
        f"<details><summary>Passage: {html.escape(label(name))}</summary>",
        "",
        f"<pre>{html.escape(passage.strip(), quote=True)}</pre>",
        "",
        "</details>",
        "",
    ]


def _fact_value(source: Source, name: str) -> str:
    fact = source.fact(name)
    if fact is None:
        return "–"
    return f"{cell(fact.observed)} ({fact.outcome})"


def card(source: Source, records: Path = paths.RECORDS) -> str:
    counts = summary(source)
    lines = [MARKER, "", f"# Data card: {cell(source.title)}", ""]
    if source.differs:
        names = ", ".join(cell(label(fact.name)) for fact in source.differs)
        lines += [
            f"> **{len(source.differs)} fact(s) differ from what docs/flood/requirements.md "
            f"says: {names}.** Under FS6 a stage that uses this source stops until the "
            "requirements are corrected.",
            "",
        ]
    lines += [
        f"Level of check (FS7): **{level_words(source, records)}**. Facts read from the primary "
        f"source on {cell(source.checked_on)} in stage {cell(source.stage)}: "
        + ", ".join(f"{counts[outcome]} {outcome}" for outcome in counts)
        + ".",
        "",
        "| | |",
        "| --- | --- |",
        f"| Publisher | {cell(source.publisher)} |",
        f"| Used for | {cell(', '.join(source.used_for))} |",
        f"| Licence | {_fact_value(source, 'licence')} |",
        f"| Coverage in space | {_fact_value(source, 'coverage_space')} |",
        f"| Coverage in time | {_fact_value(source, 'coverage_time')} |",
        f"| Release | {_fact_value(source, 'release')} |",
        "",
        "## Files fetched",
        "",
    ]
    if source.files:
        lines += [
            "Paths are relative to `data/cache/flood/` (not committed).",
            "",
            "| File | Bytes | SHA-256 | Fetched at | Address |",
            "| --- | ---: | --- | --- | --- |",
        ]
        lines += [
            f"| {cell(f.path)} | {f.bytes:,} | {cell(f.sha256)} | {cell(f.fetched_at)} "
            f"| {link(f.url)} |"
            for f in source.files
        ]
    else:
        lines.append("No file fetched for this source.")
    lines += ["", "## Known biases", "", cell(source.known_biases), "", "## Facts", ""]
    lines += [
        "Claimed is what docs/flood/requirements.md says; observed is what the primary source "
        "says. Facts after the first eight are further facts of this source.",
        "",
        "| Fact | Claimed | Observed | Outcome | Address | Note |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for fact in source.facts:
        note = " ".join(part for part in (fact.note.strip(), fact.verdict_note.strip()) if part)
        lines.append(
            f"| {cell(label(fact.name))} | {cell(fact.claimed)} | {cell(fact.observed)} "
            f"| {fact.outcome} | {link(fact.source_url)} | {cell(note)} |"
        )
    lines += ["", "### Passages", ""]
    passages = [line for fact in source.facts for line in _passage(fact.name, fact.passage)]
    lines += passages or ["No passage recorded.", ""]
    return "\n".join(lines).rstrip("\n") + "\n"


def index(sources: list[Source], records: Path = paths.RECORDS) -> str:
    lines = [
        MARKER,
        "",
        "# Data cards: flood lab",
        "",
        "One card per source whose facts were read from the primary source (FS6). "
        f"Required facts: {', '.join(label(name).lower() for name in REQUIRED)}.",
        "",
    ]
    if not sources:
        return "\n".join([*lines, "No sources checked yet.", ""])
    lines += [
        "| Source | Level (FS7) | Confirmed | Differs | Not checked | Not applicable | Stage |",
        "| --- | --- | ---: | ---: | ---: | ---: | --- |",
    ]
    for source in sources:
        counts = summary(source)
        lines.append(
            f"| [{cell(source.title)}]({source.id}.md) | {level_words(source, records)} "
            f"| {counts['confirmed']} | {counts['differs']} | {counts['not checked']} "
            f"| {counts['not applicable']} | {cell(source.stage)} |"
        )
    return "\n".join(lines) + "\n"


def documents(facts: Path = paths.FACTS, records: Path = paths.RECORDS) -> dict[str, str]:
    """File name to text, for every card and the index, as the generator would write them now."""
    sources = load_all(facts)
    files = {f"{source.id}.md": card(source, records) for source in sources}
    files[INDEX] = index(sources, records)
    return files


def stale(folder: Path, expected: dict[str, str]) -> list[str]:
    """Generated cards in the folder whose source no longer has a facts file."""
    if not folder.is_dir():
        return []
    return sorted(
        path.name
        for path in folder.glob("*.md")
        if path.name not in expected and path.read_text(encoding="utf-8").startswith(MARKER)
    )


def write(
    facts: Path = paths.FACTS, records: Path = paths.RECORDS, out: Path = paths.DATA_CARDS
) -> list[Path]:
    expected = documents(facts, records)
    for name in stale(out, expected):
        (out / name).unlink()
    written = []
    for name, text in expected.items():
        write_text_atomic(out / name, text)
        written.append(out / name)
    return written


def main() -> int:
    written = write()
    print(
        f"Flood data cards: {len(written) - 1} source card(s) and the index, "
        "in docs/flood/data-cards/"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
